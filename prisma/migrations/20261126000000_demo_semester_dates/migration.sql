-- Тестовые данные: весенний семестр 2026 (SEM26SP) переносится на 01.02.2026 - 01.07.2026,
-- чтобы можно было создать следующий семестр (с 01.09.2026) без пересечения дат.
-- Условие по дате конца делает изменение однократным.
UPDATE "semesters"
SET "start_date" = TIMESTAMPTZ '2026-02-01 00:00:00+00',
    "end_date"   = TIMESTAMPTZ '2026-07-01 00:00:00+00'
WHERE "id" = 'SEM26SP'
  AND "end_date" > TIMESTAMPTZ '2026-07-01 00:00:00+00';
